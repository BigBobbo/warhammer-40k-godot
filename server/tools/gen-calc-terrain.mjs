// Bundle the official 11e GW terrain layouts, deployment zones and mission
// matchups (already in the game: 40k/terrain_layouts, 40k/deployment_zones,
// 40k/data/40kdc) for the Combat Calc board planner.
//
// Run: cd server && npm run gen:calc-terrain
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..', '..', '40k');
const OUT = join(here, '..', 'public', 'calc', 'terrain-11e.mjs');
const rd = (p) => JSON.parse(readFileSync(p, 'utf8'));
const arr = (x) => (Array.isArray(x) ? x : Object.values(x)[0]);
const r2 = (v) => Math.round(v * 100) / 100;

const layouts = [];
for (const f of readdirSync(join(ROOT, 'terrain_layouts')).filter(f => f.endsWith('.json')).sort()) {
  const j = rd(join(ROOT, 'terrain_layouts', f));
  if (j.source !== 'gw-11e' || !j.pieces || !j.mission_matchup_id) continue;
  layouts.push({
    id: j.id,
    matchup: j.mission_matchup_id,
    variant: j.variant,
    deployment: (j.recommended_deployments ?? [])[0] ?? null,
    objectives: (j.objectives ?? []).map(o => ({ id: o.id, x: r2(o.position[0]), y: r2(o.position[1]), zone: o.zone, host: o.source_pieces ?? [] })),
    pieces: j.pieces.map(p => ({
      id: p.id,
      cls: p.piece_class,                 // 'area' | 'feature'
      h: p.height_inches ?? null,
      height: p.height ?? null,           // 'tall' | 'medium' | ...
      traits: p.traits ?? [],
      poly: (p.polygon ?? []).map(([x, y]) => [r2(x), r2(y)]),
    })),
  });
}

const deployments = {};
for (const f of readdirSync(join(ROOT, 'deployment_zones')).filter(f => f.endsWith('.json'))) {
  const j = rd(join(ROOT, 'deployment_zones', f));
  deployments[j.id] = { name: j.name, zones: j.zones.map(z => ({ player: z.player, poly: z.poly.map(p => [r2(p.x), r2(p.y)]) })) };
}

const missions = Object.fromEntries(arr(rd(join(ROOT, 'data', '40kdc', 'missions.json'))).map(m => [m.id, m.name]));
const matchups = arr(rd(join(ROOT, 'data', '40kdc', 'missionMatchups.json'))).map(m => ({
  id: m.id, mine: m.disposition, theirs: m.opponent_disposition, mission: missions[m.mission_id] ?? m.mission_id,
}));
const dispositions = arr(rd(join(ROOT, 'data', '40kdc', 'forceDispositions.json'))).map(d => ({ id: d.id, name: d.name }));

writeFileSync(OUT, `// GENERATED by server/tools/gen-calc-terrain.mjs from 40k/terrain_layouts,
// 40k/deployment_zones and 40k/data/40kdc (official 11e GW layouts). Do not edit.
// Board: 44" x 60" portrait, inches, origin top-left.
export const BOARD = { w: 44, h: 60 };
export const LAYOUTS = ${JSON.stringify(layouts)};
export const DEPLOYMENTS = ${JSON.stringify(deployments)};
export const MATCHUPS = ${JSON.stringify(matchups)};
export const DISPOSITIONS = ${JSON.stringify(dispositions)};
`);
console.log(`wrote ${layouts.length} layouts, ${Object.keys(deployments).length} deployments, ${matchups.length} matchups -> ${OUT}`);
