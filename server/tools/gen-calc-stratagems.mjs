// Bundle 11e stratagems for the combat calculator: HTML stripped, split into
// WHEN / TARGET / EFFECT / RESTRICTIONS.
//
// Sources, in order:
//  1. the game's Wahapedia import, 40k/data/Stratagems.csv (base);
//  2. a trimmed snapshot of Wahapedia's own 11e CSV export,
//     tools/data/wahapedia-11e-stratagems.psv (https://wahapedia.ru/wh40k11ed/Stratagems.csv,
//     flavour text dropped) — fills the game rows that say "Official 11e
//     effect text is not available" and adds detachments the game import
//     lacks. Matched on stratagem name + detachment name (Wahapedia files the
//     chapter detachments under SM, the game under the chapter).
// Entries still without text are kept (name, CP, phase) so they are listed.
//
// Run: cd server && npm run gen:calc-stratagems
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', '..', '40k', 'data', 'Stratagems.csv');
const SNAPSHOT = join(here, 'data', 'wahapedia-11e-stratagems.psv');
const OUT = join(here, '..', 'public', 'calc', 'stratagems-11e.mjs');

function readPsv(path) {
  const lines = readFileSync(path, 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/).filter(Boolean);
  const head = lines.shift().split('|');
  return lines.map(l => {
    const f = l.split('|');
    return Object.fromEntries(head.map((h, i) => [h, f[i] ?? '']));
  });
}
// letters and digits only: apostrophe / dash / comma variants differ between the two sources
const loose = (x) => String(x ?? '').toUpperCase().replace(/[^A-Z0-9]+/g, '');
const keyOf = (name, det) => `${loose(name)}|${loose(det)}`;
function editDistance(a, b) {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) {
    d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  }
  return d[a.length][b.length];
}
// same detachment and a name within 2 edits (typos like "FEROICITY") = the same stratagem
function nearKey(k, keys) {
  const [n, det] = k.split('|');
  for (const other of keys) {
    const [n2, det2] = other.split('|');
    if (det2 === det && Math.abs(n2.length - n.length) <= 2 && editDistance(n, n2) <= 2) return other;
  }
  return null;
}

function clean(html) {
  return String(html ?? '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/?(b|i|span|div|p|a)[^>]*>/gi, '')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&rsquo;|&#8217;/g, '’').replace(/&quot;/g, '"')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{2,}/g, '\n')
    .trim();
}

function section(text, label, next) {
  const re = new RegExp(`${label}:\\s*([\\s\\S]*?)(?=${next.map(n => `${n}:`).join('|')}|$)`, 'i');
  const m = text.match(re);
  return m ? m[1].trim() : '';
}

function entry(r, desc, source) {
  const missing = !desc || /not available/i.test(desc) || !/EFFECT:/i.test(desc);
  return {
    faction: r.faction_id,
    id: r.id,
    name: r.name,
    cp: Number(r.cp_cost) || 0,
    turn: r.turn,
    phase: r.phase,
    detachment: r.detachment,
    detachmentId: r.detachment_id,
    when: missing ? '' : section(desc, 'WHEN', ['TARGET', 'EFFECT', 'RESTRICTIONS']),
    target: missing ? '' : section(desc, 'TARGET', ['EFFECT', 'RESTRICTIONS']),
    effect: missing ? '' : section(desc, 'EFFECT', ['RESTRICTIONS']),
    restrictions: missing ? '' : section(desc, 'RESTRICTIONS', []),
    missing,
    source,
  };
}

const wahapedia = readPsv(SNAPSHOT).filter(r => r.detachment && r.name);
const byKey = new Map();
for (const r of wahapedia) {
  const desc = clean(r.description);
  if (/EFFECT:/i.test(desc) && !/not available/i.test(desc)) byKey.set(keyOf(r.name, r.detachment), { r, desc });
}

const out = [];
const seen = new Set();
let filled = 0;
const consumed = new Set();
for (const r of readPsv(SRC)) {
  const k = keyOf(r.name, r.detachment);
  if (seen.has(k)) continue; // the game import repeats a few rows verbatim
  seen.add(k);
  let desc = clean(r.description);
  let source = 'game';
  const wk = byKey.has(k) ? k : nearKey(k, byKey.keys());
  if (wk) consumed.add(wk);
  if (/not available/i.test(desc) && wk) { desc = byKey.get(wk).desc; source = 'wahapedia-export'; filled++; }
  out.push(entry(r, desc, source));
}
let added = 0;
for (const [k, { r, desc }] of byKey) {
  if (seen.has(k) || consumed.has(k)) continue;
  out.push(entry(r, desc, 'wahapedia-export'));
  added++;
}

writeFileSync(OUT, `// GENERATED by server/tools/gen-calc-stratagems.mjs from 40k/data/Stratagems.csv
// (Wahapedia 11e import). Do not edit by hand.
export const STRATAGEMS = ${JSON.stringify(out)};
`);
console.log(`wrote ${out.length} stratagems (${out.filter(s => !s.missing).length} with text; ${filled} filled and ${added} added from the Wahapedia export) -> ${OUT}`);
