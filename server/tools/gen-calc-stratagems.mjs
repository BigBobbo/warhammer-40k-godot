// Bundle the game's Wahapedia 11e stratagem import (40k/data/Stratagems.csv)
// for the combat calculator: HTML stripped, split into WHEN / TARGET /
// EFFECT / RESTRICTIONS. Entries without 11e text are kept (name, CP,
// phase) so the calculator can still list them.
//
// Run: cd server && npm run gen:calc-stratagems
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', '..', '40k', 'data', 'Stratagems.csv');
const OUT = join(here, '..', 'public', 'calc', 'stratagems-11e.mjs');

const lines = readFileSync(SRC, 'utf8').split(/\r?\n/).filter(Boolean);
const head = lines.shift().split('|');
const col = (name) => head.indexOf(name);

function clean(html) {
  return String(html ?? '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/?(b|i|span|div|p|a)[^>]*>/gi, '')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&rsquo;|&#8217;/g, '’').replace(/&quot;/g, '"')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{2,}/g, '\n')
    .trim();
}

function section(text, label, next) {
  const re = new RegExp(`${label}:\\s*([\\s\\S]*?)(?=${next.map(n => `${n}:`).join('|')}|$)`, 'i');
  const m = text.match(re);
  return m ? m[1].trim() : '';
}

const out = [];
for (const line of lines) {
  const f = line.split('|');
  const desc = clean(f[col('description')]);
  const missing = /not available/i.test(desc);
  out.push({
    faction: f[col('faction_id')],
    id: f[col('id')],
    name: f[col('name')],
    cp: Number(f[col('cp_cost')]) || 0,
    turn: f[col('turn')],
    phase: f[col('phase')],
    detachment: f[col('detachment')],
    detachmentId: f[col('detachment_id')],
    when: missing ? '' : section(desc, 'WHEN', ['TARGET', 'EFFECT', 'RESTRICTIONS']),
    target: missing ? '' : section(desc, 'TARGET', ['EFFECT', 'RESTRICTIONS']),
    effect: missing ? '' : section(desc, 'EFFECT', ['RESTRICTIONS']),
    restrictions: missing ? '' : section(desc, 'RESTRICTIONS', []),
    missing,
  });
}

writeFileSync(OUT, `// GENERATED by server/tools/gen-calc-stratagems.mjs from 40k/data/Stratagems.csv
// (Wahapedia 11e import). Do not edit by hand.
export const STRATAGEMS = ${JSON.stringify(out)};
`);
console.log(`wrote ${out.length} stratagems (${out.filter(s => !s.missing).length} with text) -> ${OUT}`);
