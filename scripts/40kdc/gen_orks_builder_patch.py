#!/usr/bin/env python3
"""Generate server/public/js/lib/orks-codex-11e-data.mjs (WP-O5).

The browser army builder runs on the vendored @alpaca-software/40kdc-data
bundle (server/public/js/vendor/40kdc-data.mjs), which predates Codex: Orks
(11th edition): its Ork detachments are the pre-codex provisional ones (Kult
of Speed with Wazblasta / Fasta Than Yooz, Taktikal Brigade with Skwad Leader
/ Mek Kaptin / Mork's Kunnin', ...) and 7 of the 15 codex detachments (Brute
Bosses, Flyboyz, Madcap Meks, Runt Swarm, Shoota Boyz, Wreckas, Wurrband) are
missing. The game's own dataset (40k/data/40kdc/*.json, refreshed from the
Wahapedia 11e codex snapshot by wahapedia-import.mjs overlay mode) has all 15
and their 38 enhancements. This script copies those records into a small ES
module that server/public/js/lib/data-patches.mjs upserts at load time — the
minified vendor bundle and the game's data are left untouched.

Usage (repo root):  python3 scripts/40kdc/gen_orks_builder_patch.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "40k" / "data" / "40kdc"
OUT = ROOT / "server" / "public" / "js" / "lib" / "orks-codex-11e-data.mjs"

DET_FIELDS = ["id", "name", "faction_id", "detachment_rule_id", "enhancement_ids", "stratagem_ids",
              "game_version", "detachment_points", "force_dispositions"]
ENH_FIELDS = ["id", "name", "detachment_id", "cost", "keyword_restrictions", "keyword_restriction_groups",
              "exclusion_keywords", "bearer_scope", "ability_id", "is_unique", "game_version",
              "points_provisional", "upgrade_tag", "max_targets", "rules_text"]


def main() -> None:
    dets = json.loads((DATA / "detachments.json").read_text(encoding="utf-8"))
    enhs = json.loads((DATA / "enhancements.json").read_text(encoding="utf-8"))
    codex_dets = [d for d in dets if d.get("faction_id") == "orks"
                  and str(d.get("game_version", {}).get("dataslate", "")).startswith("codex")]
    enh_by_id = {e["id"]: e for e in enhs}
    out_dets, out_enhs = [], []
    for d in sorted(codex_dets, key=lambda x: x["name"]):
        out_dets.append({k: d.get(k) for k in DET_FIELDS if k in d})
        for eid in d.get("enhancement_ids", []):
            e = enh_by_id.get(eid)
            if e is None:
                raise SystemExit(f"{d['id']}: enhancement {eid} missing from enhancements.json")
            if e.get("superseded_by_codex"):
                raise SystemExit(f"{d['id']}: enhancement {eid} is superseded but still listed")
            out_enhs.append({k: e.get(k) for k in ENH_FIELDS if k in e})
    if len(out_dets) != 15 or len(out_enhs) != 38:
        raise SystemExit(f"expected 15 codex detachments / 38 enhancements, got {len(out_dets)} / {len(out_enhs)}")
    body = [
        "// GENERATED by scripts/40kdc/gen_orks_builder_patch.py from",
        "// 40k/data/40kdc/{detachments,enhancements}.json (Wahapedia 11e codex import).",
        "// Do not edit by hand — re-run the script. Consumed by data-patches.mjs (WP-O5).",
        "",
        "// The 15 Codex: Orks (11e) detachments.",
        "export const ORKS_CODEX_DETACHMENTS = " + json.dumps(out_dets, indent=2, ensure_ascii=False) + ";",
        "",
        "// Their 38 enhancements (rules_text carries the printed bearer restriction;",
        "// upgrade_tag marks the Upgrades).",
        "export const ORKS_CODEX_ENHANCEMENTS = " + json.dumps(out_enhs, indent=2, ensure_ascii=False) + ";",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out_dets)} detachments, {len(out_enhs)} enhancements")


if __name__ == "__main__":
    main()
