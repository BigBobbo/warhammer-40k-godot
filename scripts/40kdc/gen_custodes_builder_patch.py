#!/usr/bin/env python3
"""Generate server/public/js/lib/custodes-codex-11e-data.mjs (WP-C46).

The browser army builder runs on the vendored @alpaca-software/40kdc-data
bundle (server/public/js/vendor/40kdc-data.mjs), which predates Codex:
Adeptus Custodes (11th edition): it lists the pre-codex detachments (Shield
Host, Talons of the Emperor, ...) and none of the 13 codex detachments or
their 29 enhancements. The game's own dataset (40k/data/40kdc/*.json, from
the Wahapedia 11e codex import) has them. This script copies the codex
detachment + enhancement records from the game's dataset into a small ES
module that server/public/js/lib/data-patches.mjs injects at load time, the
same way the Speedwaaagh! enhancements are patched in — the minified vendor
bundle and the game's data are left untouched.

Usage (repo root):  python3 scripts/40kdc/gen_custodes_builder_patch.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "40k" / "data" / "40kdc"
OUT = ROOT / "server" / "public" / "js" / "lib" / "custodes-codex-11e-data.mjs"

DET_FIELDS = ["id", "name", "faction_id", "detachment_rule_id", "enhancement_ids", "stratagem_ids",
              "game_version", "detachment_points", "force_dispositions", "tags"]
ENH_FIELDS = ["id", "name", "detachment_id", "cost", "keyword_restrictions", "ability_id", "is_unique",
              "game_version", "points_provisional", "upgrade_tag", "max_targets", "rules_text"]


def main() -> None:
    dets = json.loads((DATA / "detachments.json").read_text(encoding="utf-8"))
    enhs = json.loads((DATA / "enhancements.json").read_text(encoding="utf-8"))
    codex_dets = [d for d in dets if d.get("faction_id") == "adeptus-custodes"
                  and d.get("game_version", {}).get("dataslate") == "codex"]
    superseded = sorted(d["id"] for d in dets if d.get("faction_id") == "adeptus-custodes"
                        and d.get("superseded_by_codex"))
    enh_by_id = {e["id"]: e for e in enhs}
    units = json.loads((DATA / "units.json").read_text(encoding="utf-8"))
    unit_kws = {}
    for u in sorted(units, key=lambda x: x["id"]):
        if u.get("faction_id") == "adeptus-custodes":
            unit_kws[u["id"]] = list(u.get("keywords", [])) + list(u.get("faction_keywords", []))
    out_dets, out_enhs = [], []
    for d in sorted(codex_dets, key=lambda x: x["name"]):
        out_dets.append({k: d.get(k) for k in DET_FIELDS if k in d})
        for eid in d.get("enhancement_ids", []):
            e = enh_by_id.get(eid)
            if e is None:
                raise SystemExit(f"{d['id']}: enhancement {eid} missing from enhancements.json")
            out_enhs.append({k: e.get(k) for k in ENH_FIELDS if k in e})
    body = [
        "// GENERATED by scripts/40kdc/gen_custodes_builder_patch.py from",
        "// 40k/data/40kdc/{detachments,enhancements}.json (Wahapedia 11e codex import).",
        "// Do not edit by hand — re-run the script. Consumed by data-patches.mjs (WP-C46).",
        "",
        "// The 13 Codex: Adeptus Custodes (11e) detachments.",
        "export const CUSTODES_CODEX_DETACHMENTS = " + json.dumps(out_dets, indent=2, ensure_ascii=False) + ";",
        "",
        "// Their 29 enhancements (rules_text carries the printed bearer restriction).",
        "export const CUSTODES_CODEX_ENHANCEMENTS = " + json.dumps(out_enhs, indent=2, ensure_ascii=False) + ";",
        "",
        "// Pre-codex Custodes detachments the codex superseded (hidden from the picker).",
        "export const CUSTODES_SUPERSEDED_DETACHMENT_IDS = " + json.dumps(superseded, ensure_ascii=False) + ";",
        "",
        "// Codex keywords per Custodes datasheet id (the vendored bundle predates",
        "// TRUSTED SENTINEL / GRAV-ASSAULT): read by the builder's enhancement",
        "// bearer filter only.",
        "export const CUSTODES_CODEX_UNIT_KEYWORDS = " + json.dumps(unit_kws, indent=2, ensure_ascii=False) + ";",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out_dets)} detachments, {len(out_enhs)} enhancements, "
          f"{len(superseded)} superseded")


if __name__ == "__main__":
    main()
